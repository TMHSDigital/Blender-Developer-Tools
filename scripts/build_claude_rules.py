#!/usr/bin/env python3
"""Generate the agent-readable copies of rules/*.mdc.

Only Cursor reads .mdc rules. This writes the same plain-markdown summary (one
section per rule: description, load scope, link to the full rule with its
Wrong/Right examples) to four places:

- claude/skills/blender-rules/SKILL.md: a skill the plugin ships
  (.claude-plugin/plugin.json "skills"), so plugin users get the rules with no
  second clone; Claude loads it when writing or reviewing bpy code.
- claude/blender-rules.md: for always-on use, imported from a project's
  CLAUDE.md with ``@path/to/Blender-Developer-Tools/claude/blender-rules.md``.
- agents/AGENTS.md: for agents that read AGENTS.md (Codex, Windsurf, Gemini
  CLI, Copilot's coding agent); append it to a project's AGENTS.md (#376).
- agents/copilot/blender-python.instructions.md: a GitHub Copilot path-scoped
  instructions file (``applyTo: "**/*.py"``, the rules' own scope) for a
  project's .github/instructions/.

Links are absolute GitHub URLs so they open from an installed plugin, a
checkout, or a CLAUDE.md import alike.

    python scripts/build_claude_rules.py          # rewrite the file
    python scripts/build_claude_rules.py --check  # exit 1 if it is stale (CI)
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "claude" / "blender-rules.md"
SKILL_OUT = REPO / "claude" / "skills" / "blender-rules" / "SKILL.md"
AGENTS_OUT = REPO / "agents" / "AGENTS.md"
COPILOT_OUT = REPO / "agents" / "copilot" / "blender-python.instructions.md"
COPILOT_FRONT = """---
applyTo: "**/*.py"
---

"""
RULE_URL = "https://github.com/TMHSDigital/Blender-Developer-Tools/blob/main/rules/"
SKILL_FRONT = """---
name: blender-rules
description: Blender Python anti-pattern rules (bmesh leaks, bpy.ops in loops, deprecated context-copy overrides, bulk mesh writes, prop annotations and context guards, Extensions manifest, import scale, export modifiers, glTF/FBX axis RNA, the removed bgl module, the normals API removed in 4.1). Use when writing, reviewing or fixing any bpy / Blender add-on or script code.
---

"""


def parse(path: Path) -> tuple[str, list[str]]:
    text = path.read_text(encoding="utf-8").replace("\r\n", "\n")
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        raise SystemExit(f"{path}: missing frontmatter")
    front = m.group(1)
    desc = re.search(r"^description:\s*(.+)$", front, re.M)
    if not desc:
        raise SystemExit(f"{path}: missing description")
    globs = re.findall(r'^\s+-\s+"?([^"\n]+)"?\s*$', front.split("globs:", 1)[-1], re.M)
    return desc.group(1).strip(), globs


def render(title: str = "Blender Developer Tools rules (Claude Code)") -> str:
    lines = [
        f"# {title}",
        "",
        "<!-- Generated by scripts/build_claude_rules.py from rules/*.mdc. Do not edit. -->",
        "",
        "Apply these when writing or reviewing Blender Python. Each rule links to the",
        "full version with Wrong/Right examples.",
        "",
    ]
    for path in sorted((REPO / "rules").glob("*.mdc")):
        desc, globs = parse(path)
        lines += [
            f"## {path.stem}",
            "",
            desc,
            "",
            f"Applies to: {', '.join(f'`{g}`' for g in globs) or 'n/a'}. Full rule: [`rules/{path.name}`]({RULE_URL}{path.name}).",
            "",
        ]
    return "\n".join(lines).rstrip("\n") + "\n"


def outputs() -> dict[Path, str]:
    body = render()
    generic = render("Blender Developer Tools rules")
    return {OUT: body, SKILL_OUT: SKILL_FRONT + body, AGENTS_OUT: generic,
            COPILOT_OUT: COPILOT_FRONT + generic}


def main() -> int:
    if "--check" in sys.argv:
        stale = []
        for path, new in outputs().items():
            old = path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.exists() else ""
            if old != new:
                stale.append(path.relative_to(REPO).as_posix())
        if stale:
            print(f"{', '.join(stale)} stale; run python scripts/build_claude_rules.py",
                  file=sys.stderr)
            return 1
        print("rules exports (claude/, agents/AGENTS.md, agents/copilot/) are up to date")
        return 0
    for path, new in outputs().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(new, encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
